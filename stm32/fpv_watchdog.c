/**
 * STM32G431 Watchdog / Power Controller for FPV Ground Station
 *
 * Function:
 *  - Monitors heartbeat from Raspberry Pi via UART (115200 baud)
 *  - If heartbeat missing > WATCHDOG_TIMEOUT_MS, cuts Pi power via GPIO
 *  - Restores power after RECOVERY_DELAY_MS
 *  - Status LED blink patterns:
 *      1 Hz steady = normal
 *      5 Hz fast   = watchdog triggered, recovery in progress
 *
 * Hardware:
 *  PA2 (USART2_TX) → Pi GPIO (heartbeat RX)
 *  PA3 (USART2_RX) ← Pi GPIO (heartbeat TX)
 *  PB8             → MOSFET gate controlling Pi 5V rail
 *  PC13            → LED (active low on most Nucleo boards)
 *
 * Build: STM32CubeIDE or arm-none-eabi-gcc + STM32 HAL
 * Clock: HSI 16 MHz (no external crystal required)
 */

#include "main.h"
#include <string.h>
#include <stdint.h>

/* ── Configuration ────────────────────────────────────────────────── */
#define WATCHDOG_TIMEOUT_MS   5000U   /* 5 s without heartbeat → reset */
#define RECOVERY_DELAY_MS     3000U   /* 3 s power-off before restart  */
#define HEARTBEAT_MSG         "ALIVE\n"
#define HEARTBEAT_LEN         6U
#define UART_BAUD             115200U

/* ── Peripheral handles (generated by CubeMX or defined manually) ─── */
extern UART_HandleTypeDef huart2;

/* ── Internal state ───────────────────────────────────────────────── */
static volatile uint32_t last_heartbeat_ms = 0;
static volatile uint8_t  rx_byte           = 0;
static char              rx_buf[32]        = {0};
static uint8_t           rx_idx           = 0;

/* ── GPIO helpers ─────────────────────────────────────────────────── */
#define PI_POWER_PORT   GPIOB
#define PI_POWER_PIN    GPIO_PIN_8
#define LED_PORT        GPIOC
#define LED_PIN         GPIO_PIN_13

static inline void pi_power_on(void)  { HAL_GPIO_WritePin(PI_POWER_PORT, PI_POWER_PIN, GPIO_PIN_SET);   }
static inline void pi_power_off(void) { HAL_GPIO_WritePin(PI_POWER_PORT, PI_POWER_PIN, GPIO_PIN_RESET); }
static inline void led_on(void)       { HAL_GPIO_WritePin(LED_PORT, LED_PIN, GPIO_PIN_RESET); } /* active low */
static inline void led_off(void)      { HAL_GPIO_WritePin(LED_PORT, LED_PIN, GPIO_PIN_SET);   }
static inline void led_toggle(void)   { HAL_GPIO_TogglePin(LED_PORT, LED_PIN); }

/* ── Watchdog logic ───────────────────────────────────────────────── */
static void watchdog_reset_pi(void)
{
    pi_power_off();

    /* Fast blink during recovery */
    for (uint32_t i = 0; i < (RECOVERY_DELAY_MS / 100); i++) {
        led_toggle();
        HAL_Delay(100);
    }

    last_heartbeat_ms = HAL_GetTick(); /* reset timer before power-on */
    pi_power_on();
}

/* ── UART receive callback (1 byte at a time) ─────────────────────── */
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance != USART2) return;

    char c = (char)rx_byte;

    if (c == '\n' || rx_idx >= sizeof(rx_buf) - 1) {
        rx_buf[rx_idx] = '\0';

        if (strncmp(rx_buf, "ALIVE", 5) == 0) {
            last_heartbeat_ms = HAL_GetTick();
        }

        rx_idx = 0;
        memset(rx_buf, 0, sizeof(rx_buf));
    } else {
        rx_buf[rx_idx++] = c;
    }

    /* Re-arm single-byte receive */
    HAL_UART_Receive_IT(&huart2, &rx_byte, 1);
}

/* ── Main application ─────────────────────────────────────────────── */
void fpv_watchdog_main(void)
{
    pi_power_on();
    last_heartbeat_ms = HAL_GetTick();

    /* Start interrupt-driven receive */
    HAL_UART_Receive_IT(&huart2, &rx_byte, 1);

    uint32_t led_tick = 0;

    while (1)
    {
        uint32_t now = HAL_GetTick();

        /* Watchdog check */
        if ((now - last_heartbeat_ms) > WATCHDOG_TIMEOUT_MS) {
            watchdog_reset_pi();
        }

        /* Normal: 1 Hz LED blink */
        if ((now - led_tick) >= 500) {
            led_toggle();
            led_tick = now;
        }

        HAL_Delay(10);
    }
}
